#!/usr/bin/env node
/**
 * Generates src/v1-parity-schemas.ts from the frozen pre-migration tool-contract
 * fixtures (tests/fixtures/premigration/tool-contracts/*.json).
 *
 * Each fixture's `advertised.inputSchema` holds the VERBATIM pre-migration wire
 * bytes of that tool's advertised inputSchema in wire property order. This
 * script emits a deterministic TypeScript module keyed by tool name, preserving
 * that property order byte-for-byte (JSON.parse/JSON.stringify retain insertion
 * order for the non-integer keys used by JSON Schema).
 *
 * The generated module is the RUNTIME source for v1-parity tools/list
 * advertisement; the fixtures stay test-only evidence and are never imported
 * at runtime.
 *
 * Run with: node scripts/premigration/generate-v1-parity-schemas.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const FIXTURES_DIR = join(REPO_ROOT, "tests", "fixtures", "premigration", "tool-contracts");
const OUTPUT_PATH = join(REPO_ROOT, "src", "v1-parity-schemas.ts");

const files = readdirSync(FIXTURES_DIR)
  .filter((file) => file.endsWith(".json"))
  .sort();

const entries = [];
for (const file of files) {
  const fixture = JSON.parse(readFileSync(join(FIXTURES_DIR, file), "utf8"));
  const name = fixture?.advertised?.name;
  const inputSchema = fixture?.advertised?.inputSchema;
  if (typeof name !== "string" || name.length === 0) {
    throw new Error(`Fixture ${file} is missing advertised.name`);
  }
  if (inputSchema === undefined || inputSchema === null || typeof inputSchema !== "object") {
    throw new Error(`Fixture ${file} is missing advertised.inputSchema`);
  }
  entries.push([name, inputSchema]);
}

if (entries.length === 0) {
  throw new Error(`No tool-contract fixtures found under ${FIXTURES_DIR}`);
}

function reindent(json, pad) {
  return json
    .split("\n")
    .map((line, index) => (index === 0 ? line : pad + line))
    .join("\n");
}

const body = entries
  .map(([name, schema]) => `  ${JSON.stringify(name)}: ${reindent(JSON.stringify(schema, null, 2), "  ")}`)
  .join(",\n");

const output = `// AUTO-GENERATED by scripts/premigration/generate-v1-parity-schemas.mjs — DO NOT EDIT.
// Source of truth: tests/fixtures/premigration/tool-contracts/*.json (advertised.inputSchema,
// VERBATIM pre-migration wire bytes in wire property order). Regenerate with:
//   node scripts/premigration/generate-v1-parity-schemas.mjs

/**
 * Pre-migration (MCP SDK v1) advertised inputSchema per tool, keyed by tool
 * name. Served verbatim through the registration adapter's jsonSchema
 * Converter so tools/list advertisement stays byte-identical across the
 * v1 -> v2 migration.
 */
export const V1_PARITY_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = {
${body}
};
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`Wrote ${entries.length} tool schemas to ${OUTPUT_PATH}`);
